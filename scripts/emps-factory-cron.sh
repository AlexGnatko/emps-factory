#!/bin/bash
#
# Generate the cron schedule for the EMPS Factory scripts from factory.conf.
#
# Usage:
#   emps-factory-cron.sh              print the crontab that would be installed
#   emps-factory-cron.sh --install    write /etc/cron.d/emps-factory
#   emps-factory-cron.sh --remove     delete /etc/cron.d/emps-factory
#
# Jobs: mysql-dump-all.sh (DumpPeriod, CronMysql), files-backup.sh
# (FilesPeriod, CronFiles) and backup-check.sh (CronCheckPeriod 6h, CronCheck;
# its JSON result goes to CheckOutputFile, /var/log/backup-check.json). Other
# options: CronOffsetMinute, CronStartHour,
# CronFilesOffsetMinute, CronFilesStartHour, CronCheckOffsetMinute,
# CronCheckStartHour, CronMailTo. Re-run with --install
# after changing any of them.
#
# Schedule rules for a period:
#   shorter than a day and dividing 24 (8h, 12h, 6h...): fixed hours counted from
#       the start hour, e.g. 12h and start 3 -> 03:xx and 15:xx
#   any other shorter period: every hour (the script skips runs that are too early)
#   a day or longer (1d, 2d, 1w...): once a day at the start hour (the script
#       skips the days on which nothing is due)

set -uo pipefail

for _d in "${EF_LIB:-/usr/local/lib/emps-factory}" "$(dirname "$(readlink -f "$0")")/lib"; do
  [ -r "$_d/common.sh" ] && { . "$_d/common.sh"; break; }
done
type ef_conf_load >/dev/null 2>&1 || { echo "ERROR: common.sh not found" >&2; exit 1; }

CRON_FILE="${EF_CRON_FILE:-/etc/cron.d/emps-factory}"
SBIN="${EF_SBIN:-/usr/local/sbin}"

case "${1:-}" in
  ""|--print) MODE=print ;;
  --install)  MODE=install ;;
  --remove)   MODE=remove ;;
  -h|--help)  sed -n '3,22p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
  *) echo "usage: $0 [--print|--install|--remove]" >&2; exit 1 ;;
esac

if [ "$MODE" = remove ]; then
  rm -f -- "$CRON_FILE" && echo "Removed $CRON_FILE"
  exit 0
fi

ef_conf_load

# job_line LABEL PERIOD MINUTE HOUR0 COMMAND -> prints a comment and a cron line
job_line() {
  local label="$1" period="$2" minute="$3" hour0="$4" cmd="$5"
  local period_s step h hours field note
  period_s="$(ef_period_seconds "$period")" || ef_die "bad period '$period' for $label (use 8h, 12h, 1d, 1w ...)"
  [[ "$minute" =~ ^[0-9]+$ ]] && (( minute <= 59 )) || ef_die "$label: the minute must be 0-59"
  [[ "$hour0" =~ ^[0-9]+$ ]] && (( hour0 <= 23 )) || ef_die "$label: the start hour must be 0-23"
  minute=$((10#$minute)); hour0=$((10#$hour0))

  if (( period_s < 86400 )); then
    if (( 86400 % period_s == 0 )); then
      step=$(( period_s / 3600 )); hours=""
      for (( h = hour0 % step; h < 24; h += step )); do hours+="${hours:+,}$h"; done
      field="$hours"
      note="every $period at minute $minute, hours $hours"
    else
      field="*"
      note="every hour; the script skips runs that come before $period has passed"
    fi
  else
    field="$hour0"
    note="daily at $(printf '%02d:%02d' "$hour0" "$minute"); the script skips days when nothing is due (period $period)"
  fi
  echo
  echo "# $label: $note"
  echo "$minute $field * * * root $SBIN/$cmd >/dev/null"
}

generate() {
  echo "# Generated by emps-factory-cron.sh from $EF_CONF_FILE on $(date '+%F %T')."
  echo "# Do not edit by hand: change factory.conf and run \"emps-factory-cron.sh --install\"."
  echo "SHELL=/bin/bash"
  echo "PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
  if [ -n "$(ef_get cronmailto)" ]; then echo "MAILTO=$(ef_get cronmailto)"; fi
  if ef_bool "$(ef_get cronmysql yes)"; then
    job_line "MySQL dumps" "$(ef_get dumpperiod 1d)" \
      "$(ef_get cronoffsetminute 17)" "$(ef_get cronstarthour 3)" mysql-dump-all.sh
  fi
  if ef_bool "$(ef_get cronfiles yes)"; then
    job_line "File backups" "$(ef_get filesperiod 1d)" \
      "$(ef_get cronfilesoffsetminute 47)" "$(ef_get cronfilesstarthour 4)" files-backup.sh
  fi
  if ef_bool "$(ef_get croncheck yes)"; then
    job_line "Backup health check" "$(ef_get croncheckperiod 6h)" \
      "$(ef_get croncheckoffsetminute 0)" "$(ef_get croncheckstarthour 0)" \
      "backup-check.sh --json --output $(ef_get checkoutputfile /var/log/backup-check.json)"
  fi
}

# Build the text first so that a configuration error never leaves a half-written file
TEXT="$(generate)" || exit 1

if [ "$MODE" = print ]; then
  printf '%s\n' "$TEXT"
else
  TMP="$(mktemp)" || ef_die "cannot create a temp file"
  trap 'rm -f "$TMP"' EXIT
  printf '%s\n' "$TEXT" > "$TMP"
  install -m 644 "$TMP" "$CRON_FILE" || ef_die "cannot write $CRON_FILE"
  echo "Installed $CRON_FILE:"
  grep -v '^#' "$CRON_FILE" | sed '/^$/d'
fi
